import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve('site');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sources=[...html.matchAll(/<link\b[^>]*rel="stylesheet"[^>]*>/g)]
  .map(match=>match[0].match(/href="([^"]+)"/)?.[1]?.split('?')[0])
  .filter(href=>href && !href.includes('://') && href!=='site-styles.css');
const bundle='/* Generated by scripts/build-styles.mjs. Preserve source order. */\n'+sources.map(file=>{
  const css=fs.readFileSync(path.join(root,file),'utf8').replace(/\r\n/g,'\n');
  if(/@import\b/.test(css)) throw Error('Resolve imports before bundling '+file);
  return `\n/* ${file} */\n${css}`;
}).join('\n');
const target=path.join(root,'site-styles.css');
if(process.argv.includes('--check')) {
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==bundle) throw Error('Run node scripts/build-styles.mjs');
} else fs.writeFileSync(target,bundle);
console.log('Site stylesheet:',sources.length,'sources in the original cascade');
