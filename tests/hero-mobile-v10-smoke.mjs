import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('site/index.html'), css=read('site/hero-mobile-v10.css'), js=read('site/hero-v5.js');
assert(/<source\s+media="\(max-width: 899px\) and \(orientation: portrait\)"\s+src="assets\/media\/motion-hero-mobile.mp4"/.test(html),'HERO precisa fonte mobile 9:16 como primeira source');
assert(html.includes('hero-mobile-v10.css'),'Deve carregar CSS depois de mobile-v9.css');
assert(html.indexOf('mobile-v9.css')<html.indexOf('hero-mobile-v10.css'),'Override mobile em ordem correta');
assert(css.includes('aspect-ratio:9/16') || css.includes('aspect-ratio:9 / 16'),'Frame final deve preservar proporção vertical');
assert(/\.hero-scroll-stage \.hero-film-screen video\s*\{[\s\S]*?object-fit:cover/.test(css),'Filme deve cobrir viewport mobile sem faixa central');
assert(css.includes('mask-image:none'),'Não usar máscara central no HERO portrait');
assert(js.includes('to-hero-mobile-film-and-copy'),'ScrollTrigger mobile permanece ativo');
assert(js.includes('scheduleSeek(Math.min(1, self.progress / videoPhaseEnd)'),'Quadros vinculados a scroll progress');
assert(!html.includes('hero-bleed.js')&&!html.includes('hero-edge-canvas'),'Não pode repetir bordas');
const file=new URL('../site/assets/media/motion-hero-mobile.mp4', import.meta.url);
assert(fs.existsSync(file),'Asset mobile real precisa existir');
assert(fs.statSync(file).size>100000,'Asset mobile não pode ser arquivo vazio');
console.log('PASS mobile v10: vídeo vertical real e HeroScroll sem espelhamento');
