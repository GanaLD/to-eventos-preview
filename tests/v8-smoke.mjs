import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=(path)=>fs.readFileSync(new URL('../'+path,import.meta.url),'utf8');
const html=read('site/index.html');
const about=read('site/v7.js');
const motion=read('site/motion-v71.js');
const css=read('site/motion-v71.css');
const generator=read('scripts/render-botanical-v8.py');
const flower=html.slice(html.indexOf('<section id="sobre"'),html.indexOf('<section id="solucoes"'));
const solutions=html.slice(html.indexOf('<section id="solucoes"'),html.indexOf('<section id="projetos"'));
const projects=html.slice(html.indexOf('<section id="projetos"'),html.indexOf('<section id="contato"'));
assert(flower.includes('papoulas-completas-v8.mp4'),'Sobre deve usar uma nova animação das flores completas');
assert(flower.includes('Papoulas originais') && !flower.includes('figcaption'),'A flor não deve ter legenda decorativa');
assert(html.includes('papoulas-preview.webp'),'Arte original íntegra é a origem ou fallback visual');
assert(/#sobre \.botanical-motion\s*\{[^}]*grid-column:9\s*\/\s*span\s*4/s.test(css),'Flor deve ocupar coluna editorial correta, não coluna 2');
assert(/#sobre \.botanical-motion \.about-floral-video\s*\{[^}]*object-fit:contain/s.test(css),'Preservar aspecto e todos os pétalas');
assert(/top:\s*63%/.test(about) || about.includes("start:'top 63%'"),'Texto de Sobre só deve entrar quando for efetivamente visível');
assert(about.includes('duration:1.75')&&about.includes('stagger:.45'),'Entrada de textos deve ser mais lenta e perceptível');
assert(!about.includes('reveal?.kill()'),'Não piscar no retorno');
assert(motion.includes('to-v8-type-competence'),'Digitacão explícita em competências');
assert(motion.includes('to-v8-type-case'),'Digitação exclusiva no título do card cinza');
assert(!motion.includes('timeline.restart()'),'Não reiniciar timelines do usuário');
assert(motion.includes('containerAnimation'),'Painéis horizontais devem seguir a mesma animação do projeto');
assert(motion.includes('prefers-reduced-motion'),'Acessibilidade para movimento reduzido');
assert(projects.includes('connect-web.mp4')&&projects.includes('to-pdf-showcase'),'Manter projetos e showcase PDF');
assert(solutions.includes('solutions-floral-left')&&solutions.includes('solutions-floral-right'),'Manter as duas papoulas laterais');
assert(generator.includes('papoulas-preview.webp')&&generator.includes('movflags'),'Usar a arte original sem recorte e exportar vídeo seekable');
console.log('V8: estrutura floral íntegra e motions por seção OK');
