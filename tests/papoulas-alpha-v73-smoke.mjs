import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('site/index.html');
const css=read('site/papoulas-intactas-v76.css');
const about=html.slice(html.indexOf('id="sobre"'),html.indexOf('id="solucoes"'));
assert(about.includes('papoulas-preview.webp'),'A imagem das papoulas deve ter canal alfa nativo');
assert(!html.includes('papoulas-alpha-v73.js'),'Shader antigo desativado');
assert(!about.includes('<video'),'Não permitir bordas de vídeo recortadas');
assert(css.includes('mask-image:none') && css.includes('clip-path:none'),'Bloquear máscaras e cortes');
console.log('Papoulas RGBA V7.6: OK');
