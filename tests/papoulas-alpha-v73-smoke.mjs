import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('site/index.html');
const css=read('site/papoulas-fundo-infinito-v77.css');
const about=html.slice(html.indexOf('<section id="sobre"'),html.indexOf('<section id="solucoes"'));
assert(about.includes('class="about-floral-video"'),'Papoulas devem continuar animadas');
assert(about.includes('papoulas-invisivel-aquarela-v1.mp4?v=20261027'),'Usar o vídeo vertical novo enviado pela cliente');
assert(!html.includes('papoulas-alpha-v73.js')&&!html.includes('papoulas-alpha-v73.css'),'Não aplicar matte que suaviza as bordas das pétalas');
assert(css.includes('object-fit:contain')&&css.includes('clip-path:none')&&css.includes('mask-image:none'),'Manter o quadro integral e sem máscara');
console.log('Papoulas novas: vídeo original sem recorte ou shader: OK');
