import assert from 'node:assert/strict';
import {readFileSync, existsSync} from 'node:fs';
const read = file => readFileSync(new URL('../' + file, import.meta.url), 'utf8');
const html = read('site/index.html');
const css = read('site/whatsapp-glossy.css');
const iconPath = new URL('../site/assets/media/whatsapp-glossy.webp', import.meta.url);
const buttons = [...html.matchAll(/<a class="to-whatsapp-float"[^>]*>[\s\S]*?<\/a>/g)];
assert.equal(buttons.length, 1, 'Apenas um botão WhatsApp flutuante');
const button = buttons[0][0];
assert(button.includes('https://wa.me/5567998532167'), 'Preservar WhatsApp oficial');
assert(button.includes('target="_blank"') && button.includes('rel="noopener noreferrer"'), 'Link externo seguro');
assert(button.includes('aria-label="Abrir WhatsApp da TO Eventos"'), 'Rótulo acessível');
assert(button.includes('src="assets/media/whatsapp-glossy.webp"'), 'Usar o ícone 3D fornecido');
assert(/<img[^>]+alt=""/.test(button), 'Ícone decorativo sem leitura duplicada');
assert(!/<svg|<span|>[^<\s]+</.test(button), 'Sem ícone antigo ou texto visível');
assert(html.includes('whatsapp-glossy.css'), 'CSS do ícone carregado');
assert(existsSync(iconPath), 'Imagem precisa existir no artefato');
const image = readFileSync(iconPath);
assert(image.length > 1000 && image.subarray(0,4).toString() === 'RIFF' && image.subarray(8,12).toString() === 'WEBP','WebP real, não placeholder');
assert(css.includes('background: transparent') && css.includes('box-shadow: none'), 'Remover botão verde antigo');
assert(css.includes('width: 74px') && css.includes('width: 64px'), 'Dimensões desktop e mobile');
console.log('Botão WhatsApp 3D — estrutura e arquivo de imagem válidos');
