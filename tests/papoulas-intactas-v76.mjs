import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('site/index.html');
const css=read('site/papoulas-fundo-infinito-v77.css');
const about=html.slice(html.indexOf('id="sobre"'),html.indexOf('id="solucoes"'));
assert(about.includes('<video') && about.includes('papoulas-invisivel-aquarela-v1.mp4?v=20261027'),'Papoulas precisam usar o vídeo vertical original enviado pela cliente');
assert(!about.includes('papoulas-preview.webp'),'Nunca substituir vídeo por imagem estática');
assert(!html.includes('papoulas-alpha-v73.js'),'Nunca aplicar shader de recorte em petals');
assert(css.includes('overflow:visible') && css.includes('clip-path:none') && css.includes('mask-image:none') && css.includes('filter:none'),'Bordas livres sem recorte ou blur');
console.log('Vídeo novo de papoulas, inteiro e sem blur: OK');
