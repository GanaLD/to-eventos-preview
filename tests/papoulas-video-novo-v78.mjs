import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import fs from 'node:fs';
const read=(p)=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('site/index.html');
const flow=read('.github/workflows/pages.yml');
const css=read('site/papoulas-fundo-infinito-v77.css');
const about=html.slice(html.indexOf('<section id="sobre"'),html.indexOf('<section id="solucoes"'));
const media=fs.readFileSync(new URL('../site/assets/media/papoulas-invisivel-aquarela-v1.mp4',import.meta.url));
assert.equal(createHash('sha256').update(media).digest('hex'),'7b6e54906ecd4e6bd661c4c9f3f59ed869250f1b9a80b2d622849a51bd723a72','Arquivo deve ser exatamente o vídeo novo enviado pela cliente');
assert(flow.includes('papoulas-invisivel-aquarela-v1.mp4') && flow.includes('sha256sum -c'), 'Deploy deve validar o vídeo original');
assert(about.includes('papoulas-invisivel-aquarela-v1.mp4?v=20261027'), 'Página deve carregar a mídia nova sem cache antigo');
assert(about.includes('muted loop playsinline')&&!about.includes('autoplay'), 'Iniciar reprodução ao chegar à seção, não antes');
assert(read('site/v7.js').includes('floralObserver.observe(about)'), 'Acionar vídeo quando a seção ficar visível');
assert(!about.includes('papoulas-preview.webp'), 'Não trocar vídeo por imagem');
assert(css.includes('object-fit:contain') && css.includes('clip-path:none') && css.includes('filter:none'), 'Manter vídeo inteiro sem corte, máscara ou blur');
console.log('PASS — vídeo novo idêntico ao original, pétalas sem corte ou blur');
