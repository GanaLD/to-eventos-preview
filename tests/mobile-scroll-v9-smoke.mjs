import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const hero=read('site/hero-v5.js');
const main=read('site/main.js');
const css=read('site/mobile-v9.css');
const html=read('site/index.html');
const v7=read('site/v7.css');

assert(!/timeline\.to\(film,\s*\{autoAlpha:\s*0/.test(hero),'Hero mobile nunca pode desaparecer antes da copy');
assert(hero.includes('to-hero-mobile-film-and-copy'),'ScrollTrigger mobile deve existir');
assert(hero.includes("onUpdate: self =>"),'Timeline é dirigida pelo scroll');
assert(hero.includes('width: () => slot().width'),'Vídeo deve diminuir até o slot final no mobile');
assert(hero.includes('scheduleSeek('),'Frames de vídeo devem seguir o progresso do scroll');
assert(main.includes('if (track && pin && area)'),'Galeria de projetos precisa aceitar scroll também no mobile');
assert(main.includes('isMobile()'),'Percurso deve adaptar-se a viewport/touch');
assert(css.includes('flex-direction:row'),'Cases formam trilho horizontal sob GSAP');
assert(css.includes('.hero-visual'),'Enquadramento final precisa aparecer no mobile');
assert(css.includes('touch-action:pan-y'),'A rolagem touch vertical não pode ser bloqueada');
assert(!html.includes('hero-edge-canvas')&&!html.includes('hero-bleed.js'),'Remover espelhamento do vídeo, sem costuras');
assert(!v7.includes('HERO FULL BLEED V7.2'),'Não reintroduzir canvas do HERO');
console.log('PASS mobile V9: HeroScroll scrub, enquadramento final, scroll horizontal touch e remoção de bleed');
