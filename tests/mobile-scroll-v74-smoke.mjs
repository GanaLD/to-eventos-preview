import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('site/index.html');
const main=read('site/main.js');
const hero=read('site/hero-v5.js');
const motion=read('site/motion-v71.js');
const css=read('site/mobile-v8.css');
assert(html.includes('mobile-v8.css'),'CSS mobile final deve carregar na LP');
assert(html.indexOf('motion-v71.css')<html.indexOf('mobile-v8.css'),'Mobile V8 prevalece sobre os estilos antigos');
const mobileSource=html.match(/<source[^>]*motion-hero-mobile[^>]*>/)?.[0];
assert(mobileSource && mobileSource.includes('media="(max-width: 899px) and (orientation: portrait)"'),'Media query da fonte retrato obrigatória, independentemente da ordem de atributos');
assert(/if\s*\(track\s*&&\s*pin\s*&&\s*area\)/.test(main),'Galeria não pode ser bloqueada por breakpoint desktop');
assert(!/track\s*&&\s*pin\s*&&\s*area\s*&&\s*desktop/.test(main),'Remover a condição que quebra scroll em mobile');
assert(main.includes('mobile ?')||main.includes('isMobile() ?'),'Progressão horizontal deve ser calibrada para gesto em telas menores');
assert(css.includes('.is-gsap-active #projetos .projects-track')&&css.includes('flex-direction:row'),'Preservar track horizontal com GSAP em mobile');
assert(css.includes('height:100dvh'),'Pin horizontal precisa ocupar viewport móvel e respeitar barra do navegador');
assert(css.includes('object-fit:contain'),'Manter mídias dos projetos completas sem deformação');
assert(motion.includes('const horizontal=!!gallery?.animation'),'Animações dos cases devem acompanhar o container horizontal também no celular');
assert(hero.includes("to-hero-mobile-film-and-copy")&&hero.includes("scheduleSeek("),'Vídeo mobile dirigido pelo ScrollTrigger');
assert(hero.includes('width: () => slot().width'),'Ao terminar HeroScroll o vídeo retorna ao slot 16:9');
assert(!/timeline\.to\(film,\s*\{autoAlpha:\s*0/.test(hero),'HeroScroll mobile nunca faz sumir a mídia');
assert(!html.includes('hero-bleed.js')&&!html.includes('hero-edge-canvas'),'Não reintroduzir espelhamento nas bordas');
console.log('PASS: MOBILE TOUCH SCROLL — scrub do vídeo + galeria horizontal + media retrato');
