import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('site/index.html');
const css=read('site/papoulas-fundo-infinito-v77.css');
const js=read('site/v7.js');
const workflow=read('.github/workflows/pages.yml');
const sobre=html.slice(html.indexOf('<section id="sobre"'),html.indexOf('<section id="solucoes"'));
assert(sobre.includes('<video') && sobre.includes('class="about-floral-video"') && sobre.includes('papoulas-invisivel-aquarela-v1.mp4?v=20261027'), 'Deve usar o vídeo original novo enviado pela cliente');
assert(!sobre.includes('papoulas-preview.webp'), 'Proibir substituição do vídeo por PNG/WebP');
assert(!html.includes('papoulas-alpha-v73.js') && !html.includes('papoulas-alpha-v73.css'), 'Não carregar shader que suaviza as pétalas');
assert(css.includes('overflow:visible') && css.includes('clip-path:none') && css.includes('mask-image:none'),'Nenhuma borda geométrica recortada');
assert(css.includes('object-fit:contain') && css.includes('filter:none'), 'Vídeo deve aparecer inteiro, sem corte nem blur');
assert(workflow.includes('papoulas-invisivel-aquarela-v1.mp4') && workflow.includes('sha256sum -c'), 'Deploy deve validar e publicar o vídeo original');
assert(js.includes("el.id==='sobre-heading'?2.1:1.28"), 'Manter lettering lento de 2,1 s');
console.log('V7.7: video inteiro com fundo infinito, sem mascaras, e lettering preservado: OK');
