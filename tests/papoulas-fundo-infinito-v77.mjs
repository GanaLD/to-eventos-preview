import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('site/index.html');
const css=read('site/papoulas-fundo-infinito-v77.css');
const js=read('site/v7.js');
const encoder=read('scripts/build_papoulas_infinite.py');
const workflow=read('.github/workflows/pages.yml');
const sobre=html.slice(html.indexOf('<section id="sobre"'),html.indexOf('<section id="solucoes"'));
assert(sobre.includes('<video') && sobre.includes('class="about-floral-video"') && sobre.includes('animacao-papoulas-fundo-infinito-v77.mp4'), 'Deve usar VIDEO, nunca imagem estática');
assert(!sobre.includes('papoulas-preview.webp'), 'Proibir substituição do vídeo por PNG/WebP');
assert(!html.includes('papoulas-alpha-v73.js') && !html.includes('papoulas-intactas-v76.css'), 'Não carregar shader de recorte nem versão estática');
assert(css.includes('overflow:visible') && css.includes('clip-path:none') && css.includes('mask-image:none'),'Nenhuma borda geométrica recortada');
assert(css.includes('object-fit:contain') && !css.includes('object-fit:cover'), 'Vídeo deve aparecer inteiro, sem corte');
assert(encoder.includes('VideoCapture') && encoder.includes('libx264') && encoder.includes('padding'),'A composição infinita deve ser gerada em MP4 a partir do vídeo real e com respiro externo');
assert(encoder.includes('foreground') && encoder.includes('offwhite'), 'Preservar cores das pétalas enquanto o fundo é uniformizado');
assert(workflow.includes('build_papoulas_infinite.py') && workflow.includes('papoulas-fundo-infinito-v77.mjs'), 'Deploy deve gerar o vídeo e validar o novo componente');
assert(js.includes("el.id==='sobre-heading'?2.1:1.28"), 'Manter lettering lento de 2,1 s');
console.log('V7.7: video inteiro com fundo infinito, sem mascaras, e lettering preservado: OK');
